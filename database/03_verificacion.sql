USE barberia_unev;
SELECT DATABASE() AS base_actual, VERSION() AS version_servidor;
SHOW TABLES;
SELECT TABLE_NAME AS tabla, COLUMN_NAME AS columna, COLUMN_TYPE AS tipo,
       IS_NULLABLE AS permite_null, COLUMN_KEY AS llave
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA=DATABASE()
ORDER BY TABLE_NAME,ORDINAL_POSITION;
SELECT TABLE_NAME AS tabla, CONSTRAINT_NAME AS restriccion, COLUMN_NAME AS columna,
       REFERENCED_TABLE_NAME AS tabla_referenciada, REFERENCED_COLUMN_NAME AS columna_referenciada
FROM information_schema.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA=DATABASE() AND REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY TABLE_NAME,CONSTRAINT_NAME,ORDINAL_POSITION;
SHOW TRIGGERS;
